"""Простой детектор кризисных сообщений и тексты экстренной помощи."""
import re

_PATTERNS = [
    r"суицид", r"самоубий", r"покончить\s+с\s+собой", r"убить\s+себя",
    r"не\s+хочу\s+жить", r"хочу\s+умереть", r"лучше\s+бы\s+я\s+умер",
    r"не\s+хочу\s+больше\s+жить", r"свести\s+счёты", r"свести\s+счеты",
    r"порезать\s+себя", r"навредить\s+себе", r"наложить\s+на\s+себя\s+руки",
    r"хочу\s+исчезнуть", r"незачем\s+жить",
]
_RE = re.compile("|".join(_PATTERNS), re.IGNORECASE)

CRISIS_TEXT = (
    "Мне важно то, что ты написал(а). Ты не один и не одна.\n\n"
    "Если есть мысли о том, чтобы навредить себе, пожалуйста, свяжись с живыми людьми прямо сейчас:\n"
    "📞 Россия: <b>8-800-2000-122</b> (бесплатно, 24/7)\n"
    "🇧🇾 Беларусь: <b>8-017-352-44-44</b>\n"
    "🚑 Если опасность прямо сейчас — экстренные службы: <b>112</b>\n\n"
    "Я рядом и готов(а) продолжить разговор."
)


def is_crisis(text: str) -> bool:
    return bool(text and _RE.search(text))
